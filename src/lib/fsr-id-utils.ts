import { Firestore, collection, getDocs, doc, setDoc, deleteDoc, query, where } from 'firebase/firestore';

/**
 * Normalizes an FSR reference or ID into standard format (e.g. "FSR 0022" -> "FSR-0022", "FSR-0190" -> "FSR-0190", "116" -> "FSR-0116")
 */
export function normalizeFsrId(raw: string | undefined | null): string | null {
  if (!raw) return null;
  const str = String(raw).trim();
  if (!str) return null;

  // Ignore placeholder strings
  if (/^(NA|N\/A|NONE|DRAFT|NULL|UNDEFINED|UNSPECIFIED)$/i.test(str)) {
    return null;
  }

  // Check if matches (optional AG) FSR with separator and digits: e.g. "FSR-0190", "FSR 0123", "FSR0190", "AG-FSR-001"
  const match = str.match(/^(?:AG[-_\s]?)?FSR[-_\s#]?(\d+)$/i);
  if (match && match[1]) {
    const rawDigits = match[1];
    const num = parseInt(rawDigits, 10);
    if (!isNaN(num)) {
      // 4 or more digits: preserve exact digits (e.g. 0190 -> FSR-0190, 0022 -> FSR-0022)
      if (rawDigits.length >= 4) {
        return `FSR-${rawDigits}`;
      }
      // 3 digits: if already padded like "001" keep 3; if "190" pad to "0190"
      if (rawDigits.length === 3) {
        if (rawDigits.startsWith('00')) {
          return `FSR-${rawDigits}`;
        }
        return `FSR-0${rawDigits}`;
      }
      // 1-2 digits: pad to 4 (e.g. "22" -> "FSR-0022")
      return `FSR-${String(num).padStart(4, '0')}`;
    }
  }

  // Pure digits: e.g. "0190" -> "FSR-0190", "22" -> "FSR-0022"
  if (/^\d+$/.test(str)) {
    const num = parseInt(str, 10);
    if (!isNaN(num)) {
      if (str.length >= 4) {
        return `FSR-${str}`;
      }
      return `FSR-${String(num).padStart(4, '0')}`;
    }
  }

  // If already starts with FSR-, clean up casing and whitespace
  if (str.toUpperCase().startsWith('FSR-')) {
    const remainder = str.substring(4).trim().toUpperCase();
    if (/^\d+$/.test(remainder)) {
      return normalizeFsrId(remainder);
    }
    return `FSR-${remainder}`;
  }

  return null;
}

/**
 * Determines whether a Firestore document ID is a random auto-generated alphanumeric string
 * rather than a clean human-readable FSR number (e.g. "FSR-001", "FSR-0022", "FSR-0190").
 */
export function isAutoGeneratedId(id: string | undefined | null): boolean {
  if (!id) return false;
  const clean = String(id).trim();
  // If it matches FSR- followed by digits, it's an aligned ID
  if (/^FSR-\d+$/i.test(clean)) {
    return false;
  }
  // If it's a random 20-character Firestore ID or doesn't start with FSR-
  return true;
}

/**
 * Calculates the next unique sequential FSR ID by inspecting all existing documents in Firestore.
 */
export async function getNextFsrId(firestore: Firestore): Promise<string> {
  const snap = await getDocs(collection(firestore, 'field_service_reports'));
  let maxNum = 0;
  const usedIds = new Set<string>();

  snap.docs.forEach(d => {
    const docId = d.id.trim();
    const data = d.data();
    const ref = String(data.fsrReference || data.fsrNumber || data.reference || '').trim();

    usedIds.add(docId.toUpperCase());
    if (ref) usedIds.add(ref.toUpperCase());

    const inspectList = [docId, ref];
    inspectList.forEach(item => {
      const match = item.match(/FSR[-_\s]?(\d+)/i);
      if (match && match[1]) {
        const val = parseInt(match[1], 10);
        if (!isNaN(val) && val > maxNum && val < 100000) {
          maxNum = val;
        }
      } else if (/^\d+$/.test(item.trim())) {
        const val = parseInt(item.trim(), 10);
        if (!isNaN(val) && val > maxNum && val < 100000) {
          maxNum = val;
        }
      }
    });
  });

  let nextNum = maxNum > 0 ? maxNum + 1 : 1;
  let candidate = `FSR-${String(nextNum).padStart(4, '0')}`;

  while (usedIds.has(candidate.toUpperCase())) {
    nextNum++;
    candidate = `FSR-${String(nextNum).padStart(4, '0')}`;
  }

  return candidate;
}

/**
 * Migrates a single FSR document from an old random ID to a new clean FSR ID.
 */
export async function migrateSingleFsrDocument(
  firestore: Firestore,
  oldDocId: string,
  targetDocId: string,
  docData: Record<string, any>
): Promise<void> {
  if (oldDocId === targetDocId) return;

  const cleanData = {
    ...docData,
    id: targetDocId,
    fsrReference: targetDocId,
    migratedFromId: oldDocId,
    migratedAt: new Date().toISOString(),
  };

  // 1. Write the new document with targetDocId
  await setDoc(doc(firestore, 'field_service_reports', targetDocId), cleanData);

  // 2. Delete the old document
  await deleteDoc(doc(firestore, 'field_service_reports', oldDocId));

  // 3. Update any breakdown reports that link to oldDocId
  try {
    const bq = query(collection(firestore, 'breakdown_reports'), where('linkedToReportId', '==', oldDocId));
    const bSnap = await getDocs(bq);
    for (const bDoc of bSnap.docs) {
      await setDoc(doc(firestore, 'breakdown_reports', bDoc.id), {
        linkedToReportId: targetDocId,
        fsrReference: targetDocId,
      }, { merge: true });
    }
  } catch (e) {
    console.warn(`Could not update linked breakdowns for ${oldDocId}:`, e);
  }
}

export interface FsrAlignmentPlanItem {
  oldId: string;
  targetId: string;
  customer?: string;
  assetName?: string;
  date?: string;
  currentReference?: string;
  rawDocData: Record<string, any>;
  isExactMatch?: boolean;
}

/**
 * Scans all field_service_reports documents and prepares an alignment plan for those with random auto IDs.
 * Documents keep their current FSR reference as their new document ID whenever available.
 */
export async function planFsrAlignment(firestore: Firestore): Promise<FsrAlignmentPlanItem[]> {
  const snap = await getDocs(collection(firestore, 'field_service_reports'));

  // 1. Gather ONLY genuinely occupied document keys (already aligned FSR-XXXX documents in Firestore)
  const existingAlignedDocKeys = new Set<string>();
  let maxFoundNum = 0;

  snap.docs.forEach(d => {
    const docKey = d.id.trim();
    const data = d.data();
    const rawRef = String(data.fsrReference || data.fsrNumber || data.reference || '').trim();

    // Only reserve document keys that are ALREADY clean FSR-XXXX IDs in Firestore!
    if (!isAutoGeneratedId(docKey)) {
      existingAlignedDocKeys.add(docKey.toUpperCase());
    }

    // Track highest number across all records for fallback generation
    [docKey, rawRef].forEach(item => {
      const match = item.match(/FSR[-_\s]?(\d+)/i);
      if (match && match[1]) {
        const val = parseInt(match[1], 10);
        if (!isNaN(val) && val > maxFoundNum && val < 100000) maxFoundNum = val;
      } else if (/^\d+$/.test(item.trim())) {
        const val = parseInt(item.trim(), 10);
        if (!isNaN(val) && val > maxFoundNum && val < 100000) maxFoundNum = val;
      }
    });
  });

  // 2. Reserved keys begins ONLY with documents already occupying clean keys in Firestore
  const reservedKeys = new Set<string>(existingAlignedDocKeys);

  const plan: FsrAlignmentPlanItem[] = [];
  let nextAssignNum = maxFoundNum > 0 ? maxFoundNum + 1 : 1;

  // 3. Process unaligned documents (those with random Firestore auto-IDs)
  const unalignedDocs = snap.docs.filter(d => isAutoGeneratedId(d.id.trim()));

  for (const d of unalignedDocs) {
    const docId = d.id.trim();
    const data = d.data();
    const rawRef = String(data.fsrReference || data.fsrNumber || data.reference || '').trim();

    // Determine normalized clean reference from the document's own data
    let targetCleanId = normalizeFsrId(rawRef);
    if (!targetCleanId && data.id && !isAutoGeneratedId(String(data.id))) {
      targetCleanId = normalizeFsrId(String(data.id));
    }

    let isExactMatch = false;

    // If document has a valid FSR reference that is not yet taken by an existing document:
    if (targetCleanId && !reservedKeys.has(targetCleanId.toUpperCase())) {
      reservedKeys.add(targetCleanId.toUpperCase());
      isExactMatch = true;
    } else {
      // Only if no valid reference exists OR if there is an actual collision with an existing key,
      // allocate the next sequential number
      let candidate = `FSR-${String(nextAssignNum).padStart(4, '0')}`;
      while (reservedKeys.has(candidate.toUpperCase())) {
        nextAssignNum++;
        candidate = `FSR-${String(nextAssignNum).padStart(4, '0')}`;
      }
      targetCleanId = candidate;
      reservedKeys.add(targetCleanId.toUpperCase());
      nextAssignNum++;
      isExactMatch = false;
    }

    plan.push({
      oldId: docId,
      targetId: targetCleanId,
      customer: data.customer || 'Unknown Customer',
      assetName: data.assetName || 'Unspecified Asset',
      date: data.date || data.createdAt || 'N/A',
      currentReference: rawRef || 'None (Draft)',
      rawDocData: data,
      isExactMatch,
    });
  }

  // Sort plan by targetId in natural numerical order (FSR-0001, FSR-0022, FSR-0123, FSR-0190, etc.)
  plan.sort((a, b) => a.targetId.localeCompare(b.targetId, undefined, { numeric: true }));

  return plan;
}
