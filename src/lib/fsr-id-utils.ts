import { Firestore, collection, getDocs, doc, setDoc, deleteDoc, query, where } from 'firebase/firestore';

/**
 * Normalizes an FSR reference or ID into standard format (e.g. "FSR 0022" -> "FSR-0022", "116" -> "FSR-0116")
 */
export function normalizeFsrId(raw: string | undefined | null): string | null {
  if (!raw) return null;
  const str = String(raw).trim();
  if (!str) return null;

  // Check if matches FSR-XXXX or FSR XXXX or FSR_XXXX
  const match = str.match(/^FSR[-_\s]?(\d+)$/i);
  if (match && match[1]) {
    const num = parseInt(match[1], 10);
    if (!isNaN(num)) {
      // If 1-3 digits and was padded with 3, keep 3 or pad to 4 (e.g. 001 -> FSR-001 or FSR-0022)
      const digits = match[1].length >= 4 ? match[1] : String(num).padStart(match[1].length === 3 ? 3 : 4, '0');
      return `FSR-${digits}`;
    }
  }

  // Pure digits: e.g. "22" -> "FSR-0022"
  if (/^\d+$/.test(str)) {
    const num = parseInt(str, 10);
    if (!isNaN(num)) {
      return `FSR-${String(num).padStart(4, '0')}`;
    }
  }

  // If already starts with FSR-, clean up casing and whitespace
  if (str.toUpperCase().startsWith('FSR-')) {
    return `FSR-${str.substring(4).trim().toUpperCase()}`;
  }

  return null;
}

/**
 * Determines whether a Firestore document ID is a random auto-generated alphanumeric string
 * rather than a clean human-readable FSR number (e.g. "FSR-001", "FSR-0022").
 */
export function isAutoGeneratedId(id: string | undefined | null): boolean {
  if (!id) return false;
  const clean = String(id).trim();
  // If it matches FSR- followed by digits, it's an aligned ID
  if (/^FSR-\d+$/i.test(clean)) {
    return false;
  }
  // If it's a random 20-character Firestore ID or doesn't start with FSR-
  return true;
}

/**
 * Calculates the next unique sequential FSR ID by inspecting all existing documents in Firestore.
 */
export async function getNextFsrId(firestore: Firestore): Promise<string> {
  const snap = await getDocs(collection(firestore, 'field_service_reports'));
  let maxNum = 0;
  const usedIds = new Set<string>();

  snap.docs.forEach(d => {
    const docId = d.id.trim();
    const data = d.data();
    const ref = String(data.fsrReference || '').trim();

    usedIds.add(docId.toUpperCase());
    if (ref) usedIds.add(ref.toUpperCase());

    const inspectList = [docId, ref];
    inspectList.forEach(item => {
      const match = item.match(/FSR[-_\s]?(\d+)/i);
      if (match && match[1]) {
        const val = parseInt(match[1], 10);
        if (!isNaN(val) && val > maxNum && val < 100000) {
          maxNum = val;
        }
      } else if (/^\d+$/.test(item.trim())) {
        const val = parseInt(item.trim(), 10);
        if (!isNaN(val) && val > maxNum && val < 100000) {
          maxNum = val;
        }
      }
    });
  });

  let nextNum = maxNum > 0 ? maxNum + 1 : 1;
  let candidate = `FSR-${String(nextNum).padStart(4, '0')}`;

  while (usedIds.has(candidate.toUpperCase())) {
    nextNum++;
    candidate = `FSR-${String(nextNum).padStart(4, '0')}`;
  }

  return candidate;
}

/**
 * Migrates a single FSR document from an old random ID to a new clean FSR ID.
 */
export async function migrateSingleFsrDocument(
  firestore: Firestore,
  oldDocId: string,
  targetDocId: string,
  docData: Record<string, any>
): Promise<void> {
  if (oldDocId === targetDocId) return;

  const cleanData = {
    ...docData,
    id: targetDocId,
    fsrReference: targetDocId,
    migratedFromId: oldDocId,
    migratedAt: new Date().toISOString(),
  };

  // 1. Write the new document with targetDocId
  await setDoc(doc(firestore, 'field_service_reports', targetDocId), cleanData);

  // 2. Delete the old document
  await deleteDoc(doc(firestore, 'field_service_reports', oldDocId));

  // 3. Update any breakdown reports that link to oldDocId
  try {
    const bq = query(collection(firestore, 'breakdown_reports'), where('linkedToReportId', '==', oldDocId));
    const bSnap = await getDocs(bq);
    for (const bDoc of bSnap.docs) {
      await setDoc(doc(firestore, 'breakdown_reports', bDoc.id), {
        linkedToReportId: targetDocId,
        fsrReference: targetDocId,
      }, { merge: true });
    }
  } catch (e) {
    console.warn(`Could not update linked breakdowns for ${oldDocId}:`, e);
  }
}

export interface FsrAlignmentPlanItem {
  oldId: string;
  targetId: string;
  customer?: string;
  assetName?: string;
  date?: string;
  currentReference?: string;
  rawDocData: Record<string, any>;
}

/**
 * Scans all field_service_reports documents and prepares an alignment plan for those with random auto IDs.
 */
export async function planFsrAlignment(firestore: Firestore): Promise<FsrAlignmentPlanItem[]> {
  const snap = await getDocs(collection(firestore, 'field_service_reports'));
  const existingIds = new Set<string>();
  let maxNum = 0;

  // First pass: gather existing clean IDs and maximum number
  snap.docs.forEach(d => {
    existingIds.add(d.id.trim().toUpperCase());
    const ref = String(d.data().fsrReference || '').trim();
    if (ref) existingIds.add(ref.toUpperCase());

    [d.id, ref].forEach(item => {
      const match = item.match(/FSR[-_\s]?(\d+)/i);
      if (match && match[1]) {
        const val = parseInt(match[1], 10);
        if (!isNaN(val) && val > maxNum && val < 100000) maxNum = val;
      }
    });
  });

  const plan: FsrAlignmentPlanItem[] = [];
  let nextAssignNum = maxNum > 0 ? maxNum + 1 : 1;

  // Second pass: identify unaligned documents
  snap.docs.forEach(d => {
    const docId = d.id.trim();
    if (isAutoGeneratedId(docId)) {
      const data = d.data();
      const currentRef = String(data.fsrReference || '').trim();
      let targetCleanId = normalizeFsrId(currentRef);

      // If no valid target ID or if targetCleanId is already taken by another document
      if (!targetCleanId || (existingIds.has(targetCleanId.toUpperCase()) && targetCleanId.toUpperCase() !== docId.toUpperCase())) {
        let candidate = `FSR-${String(nextAssignNum).padStart(4, '0')}`;
        while (existingIds.has(candidate.toUpperCase())) {
          nextAssignNum++;
          candidate = `FSR-${String(nextAssignNum).padStart(4, '0')}`;
        }
        targetCleanId = candidate;
        existingIds.add(targetCleanId.toUpperCase());
        nextAssignNum++;
      } else {
        existingIds.add(targetCleanId.toUpperCase());
      }

      plan.push({
        oldId: docId,
        targetId: targetCleanId,
        customer: data.customer || 'Unknown Customer',
        assetName: data.assetName || 'Unspecified Asset',
        date: data.date || data.createdAt || 'N/A',
        currentReference: currentRef || 'None (Draft)',
        rawDocData: data,
      });
    }
  });

  return plan;
}
